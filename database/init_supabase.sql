-- 7. Funciones RPC para PostgreSQL (Supabase)
-- Permiten agregaciones ultra rápidas en el servidor de base de datos
-- ============================================================================

-- RPC: Ranking global de usuarios (Ultra rápido en PostgreSQL)
CREATE OR REPLACE FUNCTION public.get_trucky_users_ranking(
  p_start_date TIMESTAMPTZ DEFAULT NULL,
  p_end_date TIMESTAMPTZ DEFAULT NULL,
  p_status TEXT DEFAULT 'completed',
  p_include_no_company BOOLEAN DEFAULT TRUE,
  p_company_ids BIGINT[] DEFAULT NULL,
  p_limit INTEGER DEFAULT 100
)
RETURNS TABLE (
  driver_id BIGINT,
  total_distance_km NUMERIC,
  total_jobs BIGINT,
  company_count BIGINT,
  jobs_without_company BIGINT,
  last_job_at TIMESTAMPTZ,
  driver_name TEXT,
  avatar_url TEXT,
  public_url TEXT
) AS $$
BEGIN
  RETURN QUERY
  WITH driver_stats AS (
    SELECT
      j.driver_id,
      COALESCE(SUM(COALESCE(j.driven_distance_km, j.real_driven_distance_km, 0)), 0) AS total_distance,
      COUNT(j.id) AS jobs_count,
      COUNT(DISTINCT CASE WHEN j.company_id IS NOT NULL AND j.company_id > 0 THEN j.company_id END) AS comp_count,
      COUNT(CASE WHEN j.company_id IS NULL OR j.company_id <= 0 THEN 1 END) AS no_comp_jobs,
      MAX(COALESCE(j.updated_at, j.created_at)) AS latest_job_at
    FROM public.jobs_webhooks j
    WHERE
      j.driver_id IS NOT NULL 
      AND j.driver_id > 0
      AND (p_status = 'all' OR j.status = p_status)
      AND (p_start_date IS NULL OR j.created_at >= p_start_date)
      AND (p_end_date IS NULL OR j.created_at < p_end_date)
      AND (p_include_no_company OR (j.company_id IS NOT NULL AND j.company_id > 0))
      AND (p_company_ids IS NULL OR ARRAY_LENGTH(p_company_ids, 1) = 0 OR j.company_id = ANY(p_company_ids))
    GROUP BY j.driver_id
    ORDER BY total_distance DESC, jobs_count DESC
    LIMIT p_limit
  ),
  latest_driver_info AS (
    SELECT DISTINCT ON (j.driver_id)
      j.driver_id,
      COALESCE(j.raw->'data'->'driver'->>'name', 'Usuario ' || j.driver_id::text) AS name,
      j.raw->'data'->'driver'->>'avatar_url' AS avatar,
      COALESCE(j.raw->'data'->'driver'->>'public_url', 'https://hub.truckyapp.com/user/' || j.driver_id::text) AS url
    FROM public.jobs_webhooks j
    INNER JOIN driver_stats ds ON ds.driver_id = j.driver_id
    ORDER BY j.driver_id, j.created_at DESC
  )
  SELECT
    ds.driver_id,
    FLOOR(ds.total_distance)::NUMERIC AS total_distance_km,
    ds.jobs_count AS total_jobs,
    ds.comp_count AS company_count,
    ds.no_comp_jobs AS jobs_without_company,
    ds.latest_job_at AS last_job_at,
    COALESCE(ldi.name, 'Usuario ' || ds.driver_id::text) AS driver_name,
    ldi.avatar AS avatar_url,
    COALESCE(ldi.url, 'https://hub.truckyapp.com/user/' || ds.driver_id::text) AS public_url
  FROM driver_stats ds
  LEFT JOIN latest_driver_info ldi ON ldi.driver_id = ds.driver_id
  ORDER BY ds.total_distance DESC, ds.jobs_count DESC;
END;
$$ LANGUAGE plpgsql STABLE;

-- ============================================================================
-- 8. Seguridad: Row Level Security (RLS) y Políticas
-- ============================================================================

-- Habilitar RLS en todas las tablas
ALTER TABLE public.trucky_companies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jobs_webhooks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trucky_route_cache ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trucky_top_km_cache ENABLE ROW LEVEL SECURITY;

-- Políticas de lectura pública para `anon` y `authenticated`
DROP POLICY IF EXISTS "Public Read trucky_companies" ON public.trucky_companies;
CREATE POLICY "Public Read trucky_companies" ON public.trucky_companies
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public Read jobs_webhooks" ON public.jobs_webhooks;
CREATE POLICY "Public Read jobs_webhooks" ON public.jobs_webhooks
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public Read trucky_route_cache" ON public.trucky_route_cache;
CREATE POLICY "Public Read trucky_route_cache" ON public.trucky_route_cache
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public Read trucky_top_km_cache" ON public.trucky_top_km_cache;
CREATE POLICY "Public Read trucky_top_km_cache" ON public.trucky_top_km_cache
  FOR SELECT USING (true);

-- Políticas de escritura para `service_role` (API backend)
DROP POLICY IF EXISTS "Service Role All trucky_companies" ON public.trucky_companies;
CREATE POLICY "Service Role All trucky_companies" ON public.trucky_companies
  FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Service Role All jobs_webhooks" ON public.jobs_webhooks;
CREATE POLICY "Service Role All jobs_webhooks" ON public.jobs_webhooks
  FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Service Role All trucky_route_cache" ON public.trucky_route_cache;
CREATE POLICY "Service Role All trucky_route_cache" ON public.trucky_route_cache
  FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Service Role All trucky_top_km_cache" ON public.trucky_top_km_cache;
CREATE POLICY "Service Role All trucky_top_km_cache" ON public.trucky_top_km_cache
  FOR ALL TO service_role USING (true) WITH CHECK (true);

-- Permisos de lectura/escritura en esquema público
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL TABLES IN SCHEMA public TO service_role;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO anon, authenticated;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO service_role;
