-- ============================================================================
-- SQL INITIALIZATION SCRIPT FOR TRUCKY / PERUSERVER (SUPABASE / POSTGRESQL)
-- ============================================================================
-- Este script crea todas las tablas, índices, funciones, triggers y políticas RLS
-- necesarias para ejecutar la API de Trucky / PeruServer en Supabase (PostgreSQL).
-- ============================================================================

-- 1. Extensiones necesarias
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ============================================================================
-- 2. Función genérica para actualización automática de `updated_at`
-- ============================================================================
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ============================================================================
-- 3. Tabla: `trucky_companies`
-- Almacena las empresas / VTC registradas en Trucky
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.trucky_companies (
  company_id BIGINT PRIMARY KEY,
  name TEXT NOT NULL,
  tag TEXT DEFAULT '',
  avatar_url TEXT,
  cover_url TEXT,
  public_url TEXT,
  members_count INTEGER DEFAULT 0,
  country_code VARCHAR(10) DEFAULT 'PE',
  recruitment VARCHAR(50) DEFAULT 'open',
  slogan TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Índices para `trucky_companies`
CREATE INDEX IF NOT EXISTS idx_trucky_companies_name ON public.trucky_companies(name);
CREATE INDEX IF NOT EXISTS idx_trucky_companies_tag ON public.trucky_companies(tag);
CREATE INDEX IF NOT EXISTS idx_trucky_companies_country ON public.trucky_companies(country_code);
CREATE INDEX IF NOT EXISTS idx_trucky_companies_updated_at ON public.trucky_companies(updated_at DESC);

-- Trigger para `trucky_companies`
DROP TRIGGER IF EXISTS trigger_trucky_companies_updated_at ON public.trucky_companies;
CREATE TRIGGER trigger_trucky_companies_updated_at
BEFORE UPDATE ON public.trucky_companies
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();

